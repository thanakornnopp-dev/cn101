import random

def main():
    numbers = []
    # 1. สุ่มจำนวนเต็ม 10 จำนวนในช่วง 111 - 499 เก็บลงใน List
    for _ in range(10):
        val = random.randint(111, 499)
        numbers.append(val)

    # 2. ตรวจสอบและแสดงผลว่าแต่ละตัวใน List เป็นเลขคู่หรือเลขคี่
    for x in numbers:
        if x % 2 == 0:
            print(f"{x} is even")
        else:
            print(f"{x} is odd")

if __name__ == '__main__':
    main()
