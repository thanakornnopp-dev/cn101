import random

def main():
    menus = []
    # 1. รับชื่ออาหาร 5 รายการจากผู้ใช้และเพิ่มลงใน List ทีละรายการ
    for i in range(1, 6):
        food = input(f"Enter menu #{i}: ")
        menus.append(food)

    # 2. สุ่มตัวเลขจำนวนเต็มจาก 1 ถึง 5 จำนวน 3 ครั้ง
    for _ in range(3):
        order = random.randint(1, 5)
        # แสดงผลลำดับที่สุ่มได้และชื่ออาหาร (Index = order - 1)
        print(f"random output is {order}: {menus[order - 1]}")

if __name__ == '__main__':
    main()
