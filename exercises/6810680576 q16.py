import random

def main():
    # 1. สุ่มจำนวนวิชาในช่วง 3 ถึง 5
    n = random.randint(3, 5)
    print(f"The number of course is {n}.")

    # 2. สร้าง Tuple ว่างเพื่อเก็บรหัสวิชา
    courses = ()

    # 3. รับค่า Course ID ทีละค่าแล้วเพิ่มเข้าไปใน Tuple
    for _ in range(n):
        cid = input("Enter Course ID: ")
        # กฎเหล็ก: ต้องมี comma (cid,) เพื่อสร้าง 1-element tuple
        courses += (cid,)

    # 4. แสดงข้อมูลทั้งหมดใน Tuple
    print(courses)

if __name__ == '__main__':
    main()
